README_TEMPLATE = """# {loop_name}

Generated by LoopForge export (`{target}`).

## Run

```bash
python run.py
python run.py --json
```

Spec: `spec.yaml` (copied from source LSS).

Workers in spec: {workers}
"""


def load_spec(path: Path) -> dict[str, Any]:
    with path.open(encoding="utf-8") as fh:
        data = yaml.safe_load(fh)
    if not isinstance(data, dict):
        raise ValueError(f"Invalid spec: {path}")
    return data


def export_stub(spec_path: Path, out_dir: Path, target: str) -> Path:
    spec = load_spec(spec_path)
    loop_name = spec.get("loop_name", spec_path.stem)
    objective = str(spec.get("objective", "")).split("\n")[0][:120]
    workers = ", ".join(w.get("id", "?") for w in (spec.get("workers") or []))

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "spec.yaml").write_text(spec_path.read_text(encoding="utf-8"), encoding="utf-8")

    if target == "generic":
        run_src = GENERIC_RUN_PY.format(loop_name=loop_name)
    elif target == "langgraph":
        run_src = LANGGRAPH_RUN_PY.format(loop_name=loop_name, objective_short=objective.replace('"', "'"))
    elif target == "crewai":
        run_src = CREWAI_RUN_PY.format(loop_name=loop_name)
    else:
        raise ValueError(f"Unknown export target: {target}")

    (out_dir / "run.py").write_text(run_src, encoding="utf-8")
    (out_dir / "README.md").write_text(
        README_TEMPLATE.format(loop_name=loop_name, target=target, workers=workers or "none"),
        encoding="utf-8",
    )
    return out_dir
